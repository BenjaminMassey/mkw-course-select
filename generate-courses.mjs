#!/usr/bin/env node
/**
 * Derives the course list from images/courses/ and writes it to courses.js.
 *
 * The files in images/courses/ are the single source of truth for which
 * courses exist. After adding or removing course images, run:
 *
 *     node generate-courses.mjs
 *
 * and commit the regenerated courses.js.
 */
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const coursesDir = join(root, "images", "courses");
const mapsDir = join(root, "images", "maps");
const outFile = join(root, "courses.js");

const toCourseId = (name) =>
    name.endsWith(".webp") ? name.slice(0, -".webp".length) : null;

const courses = (await readdir(coursesDir))
    .map(toCourseId)
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b));

if (courses.length === 0) {
    console.error(`No .webp files found in ${coursesDir}`);
    process.exit(1);
}

// Warn about characters that are invalid in Windows filenames so the repo
// stays usable there. Use percent-encoding (e.g. "%3F" for "?") instead.
const windowsInvalid = /[?:"\\|<>*]/;
for (const course of courses) {
    if (windowsInvalid.test(course)) {
        console.warn(`warning: "${course}" contains characters that are invalid in Windows filenames (use percent-encoding, e.g. "%3F" for "?")`);
    }
}

// Sanity check: images/maps/ should have the same set of courses.
try {
    const maps = (await readdir(mapsDir)).map(toCourseId).filter(Boolean);
    for (const missing of courses.filter((c) => !maps.includes(c))) {
        console.warn(`warning: no map for course "${missing}" (missing images/maps/${missing}.webp)`);
    }
    for (const extra of maps.filter((m) => !courses.includes(m))) {
        console.warn(`warning: extra map without course "${extra}" (images/maps/${extra}.webp)`);
    }
} catch {
    console.warn(`warning: ${mapsDir} not found, skipping map check`);
}

const lines = [
    "// Generated by generate-courses.mjs from images/courses/*.webp.",
    "// Do not edit by hand; re-run `node generate-courses.mjs` after changing",
    "// the course images, then commit this file.",
    "",
    `window.COURSES = ${JSON.stringify(courses, null, 4)};`,
    "",
];

await writeFile(outFile, lines.join("\n"));
console.log(`Wrote ${outFile} with ${courses.length} courses.`);
