#!/usr/bin/env node
/**
 * Derives the course lists from images/courses/ and writes them to courses.js.
 *
 * The files in images/courses/ are the single source of truth for which
 * courses exist: base courses live directly in images/courses/, retro
 * courses in images/courses/retro/. After adding or removing course images,
 * run:
 *
 *     node generate-courses.mjs
 *
 * and commit the regenerated courses.js.
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const coursesDir = join(root, "images", "courses");
const mapsDir = join(root, "images", "maps");
const numbersDir = join(root, "images", "numbers");
const outFile = join(root, "courses.js");

const toCourseId = (name) =>
    name.endsWith(".webp") ? name.slice(0, -".webp".length) : null;

async function readCourseIds(dir) {
    return (await readdir(dir))
        .map(toCourseId)
        .filter(Boolean)
        .sort((a, b) => a.localeCompare(b));
}

const courses = await readCourseIds(coursesDir);
let retroCourses = [];
try {
    retroCourses = await readCourseIds(join(coursesDir, "retro"));
} catch {
    console.warn(`warning: ${join(coursesDir, "retro")} not found, no retro courses`);
}

if (courses.length === 0) {
    console.error(`No .webp files found in ${coursesDir}`);
    process.exit(1);
}

// Course names are used as ids, so the same name in both folders would be
// ambiguous.
for (const dup of retroCourses.filter((c) => courses.includes(c))) {
    console.error(`"${dup}" exists in both images/courses/ and images/courses/retro/`);
    process.exit(1);
}

// Warn about characters that are invalid in Windows filenames so the repo
// stays usable there. Use percent-encoding (e.g. "%3F" for "?") instead.
const windowsInvalid = /[?:"\\|<>*]/;
for (const course of [...courses, ...retroCourses]) {
    if (windowsInvalid.test(course)) {
        console.warn(`warning: "${course}" contains characters that are invalid in Windows filenames (use percent-encoding, e.g. "%3F" for "?")`);
    }
}

// Sanity check: images/maps/ (and images/maps/retro/) should have the same
// set of courses.
async function checkMaps(list, subdir) {
    const dir = join(mapsDir, subdir);
    const prefix = "images/maps/" + (subdir ? subdir + "/" : "");
    try {
        const maps = await readCourseIds(dir);
        for (const missing of list.filter((c) => !maps.includes(c))) {
            console.warn(`warning: no map for course "${missing}" (missing ${prefix}${missing}.webp)`);
        }
        for (const extra of maps.filter((m) => !list.includes(m))) {
            console.warn(`warning: extra map without course "${extra}" (${prefix}${extra}.webp)`);
        }
    } catch {
        if (list.length > 0) {
            console.warn(`warning: ${dir} not found, skipping map check`);
        }
    }
}
await checkMaps(courses, "");
await checkMaps(retroCourses, "retro");

const lines = [
    "// Generated by generate-courses.mjs from images/courses/*.webp and",
    "// images/courses/retro/*.webp.",
    "// Do not edit by hand; re-run `node generate-courses.mjs` after changing",
    "// the course images, then commit this file.",
    "",
    `window.COURSES = ${JSON.stringify(courses, null, 4)};`,
    "",
    `window.RETRO_COURSES = ${JSON.stringify(retroCourses, null, 4)};`,
    "",
];

await writeFile(outFile, lines.join("\n"));
console.log(`Wrote ${outFile} with ${courses.length} courses and ${retroCourses.length} retro courses.`);

// The map marks each course in the history with its pick number, so there
// can be one number per course. Write images/numbers/1.svg .. N.svg (50x50,
// red text with a dark outline on a transparent background) and remove any
// left over from a larger course list.
const total = courses.length + retroCourses.length;
const numberSvg = (n) => {
    const fontSize = String(n).length >= 3 ? 26 : 36;
    return [
        `<svg xmlns="http://www.w3.org/2000/svg" width="50" height="50" viewBox="0 0 50 50">`,
        `    <text x="25" y="25" text-anchor="middle" dominant-baseline="central"`,
        `        font-family="Arial, Helvetica, sans-serif" font-weight="bold"`,
        `        font-size="${fontSize}" fill="red" stroke="black" stroke-width="5"`,
        `        stroke-linejoin="round" paint-order="stroke">${n}</text>`,
        `</svg>`,
        "",
    ].join("\n");
};
await mkdir(numbersDir, { recursive: true });
for (let n = 1; n <= total; n++) {
    await writeFile(join(numbersDir, `${n}.svg`), numberSvg(n));
}
let removed = 0;
for (const name of await readdir(numbersDir)) {
    const match = /^(\d+)\.svg$/.exec(name);
    if (match && Number(match[1]) > total) {
        await rm(join(numbersDir, name));
        removed++;
    }
}
console.log(`Wrote ${total} number images to ${numbersDir}` + (removed ? ` (removed ${removed} unused).` : "."));
